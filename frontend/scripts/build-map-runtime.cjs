// Leaflet is bundled into the native WebView; no remote script or API credentials are loaded.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const leaflet=path.dirname(require.resolve('leaflet/package.json'));
const js=fs.readFileSync(path.join(leaflet,'dist/leaflet.js'),'utf8');
const css=fs.readFileSync(path.join(leaflet,'dist/leaflet.css'),'utf8');
fs.writeFileSync(path.join(root,'src/maps/vendor.ts'),'// Leaflet 1.9.4 — BSD-2-Clause. Generated by scripts/build-map-runtime.cjs.\nexport const leafletJs='+JSON.stringify(js)+';\nexport const leafletCss='+JSON.stringify(css)+';\n');
fs.copyFileSync(path.join(leaflet,'LICENSE'),path.join(root,'src/maps/LEAFLET-LICENSE'));
