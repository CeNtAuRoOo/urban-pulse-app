
package es.grupo18.urbanpulse.urban_context.integration;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.utility.DockerImageName;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;

@Testcontainers
class UrbanAssetControllerIT {

    @Container
    static final PostgreSQLContainer<?> POSTGRES =
            new PostgreSQLContainer<>(
                    DockerImageName.parse("postgis/postgis:18-3.6-alpine")
                            .asCompatibleSubstituteFor("postgres")
            );

    private static Connection connection;

    @BeforeAll
    static void setUp() throws Exception {
        connection = DriverManager.getConnection(
                POSTGRES.getJdbcUrl(),
                POSTGRES.getUsername(),
                POSTGRES.getPassword()
        );

        try (Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE EXTENSION IF NOT EXISTS postgis
                    """);

            statement.execute("""
                    CREATE SCHEMA IF NOT EXISTS cartografia
                    """);

            statement.execute("""
                    CREATE TABLE IF NOT EXISTS cartografia.contexto_urbano (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        source_table VARCHAR(64) NOT NULL,
                        name VARCHAR(255),
                        category VARCHAR(64),
                        description VARCHAR(500),
                        address VARCHAR(255),
                        phone VARCHAR(32),
                        email VARCHAR(128),
                        url VARCHAR(512),
                        geom geometry(Geometry, 25830)
                    )
                    """);
        }
    }

    @AfterAll
    static void tearDown() throws Exception {
        if (connection != null && !connection.isClosed()) {
            connection.close();
        }
    }

    @Test
    void databaseUsesPostgreSQL18AndPostGIS() throws Exception {
        try (Statement statement = connection.createStatement()) {
            try (ResultSet result = statement.executeQuery(
                    "SELECT current_setting('server_version')")) {

                Assertions.assertTrue(result.next());

                String version = result.getString(1);

                Assertions.assertTrue(
                        version.startsWith("18."),
                        "Se esperaba PostgreSQL 18, pero se encontró: " + version
                );
            }

            try (ResultSet result = statement.executeQuery(
                    "SELECT PostGIS_Version()")) {

                Assertions.assertTrue(result.next());

                String postgisVersion = result.getString(1);

                Assertions.assertNotNull(postgisVersion);
                Assertions.assertFalse(postgisVersion.isBlank());
            }
        }
    }

    @Test
    void databaseSupportsUUIDv7() throws Exception {
        try (Statement statement = connection.createStatement();
             ResultSet result = statement.executeQuery(
                     "SELECT uuidv7()::text")) {

            Assertions.assertTrue(result.next());

            String uuid = result.getString(1);

            Assertions.assertNotNull(uuid);
            Assertions.assertTrue(
                    uuid.matches(
                            "[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-7[0-9a-fA-F]{3}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}"
                    ),
                    "El UUID generado no tiene versión 7: " + uuid
            );
        }
    }

    @Test
    void urbanAssetGeometryColumnUsesSRID25830() throws Exception {
        try (Statement statement = connection.createStatement();
             ResultSet result = statement.executeQuery("""
                     SELECT Find_SRID(
                         'cartografia',
                         'contexto_urbano',
                         'geom'
                     )
                     """)) {

            Assertions.assertTrue(result.next());

            Assertions.assertEquals(25830, result.getInt(1));
        }
    }

    @Test
    void postgisCanStoreAndMeasureGeometryInMeters() throws Exception {
        try (Statement statement = connection.createStatement();
             ResultSet result = statement.executeQuery("""
                     SELECT ST_Distance(
                         ST_SetSRID(ST_MakePoint(239000, 4140000), 25830),
                         ST_SetSRID(ST_MakePoint(239300, 4140000), 25830)
                     )
                     """)) {

            Assertions.assertTrue(result.next());

            Assertions.assertEquals(
                    300.0,
                    result.getDouble(1),
                    0.001
            );
        }
    }
}
