
-- Enable PostGIS extension
CREATE EXTENSION IF NOT EXISTS postgis;

-- Create cartografia schema
CREATE SCHEMA IF NOT EXISTS cartografia;

-- Create unified urban context table
CREATE TABLE cartografia.contexto_urbano (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    source_table VARCHAR(64) NOT NULL,
    name VARCHAR(255),
    category VARCHAR(64),
    description VARCHAR(500),
    address VARCHAR(255),
    phone VARCHAR(32),
    email VARCHAR(128),
    url VARCHAR(512),

    -- PostGIS geometry with SRID 25830 (ETRS89 / UTM zone 30N)
    geom geometry(Geometry, 25830)
);

-- Spatial index using PostGIS GiST
CREATE INDEX idx_contexto_urbano_geom
    ON cartografia.contexto_urbano
    USING GIST (geom);

-- Index to filter assets by their original source table
CREATE INDEX idx_contexto_urbano_source_table
    ON cartografia.contexto_urbano (source_table);
